import { randomBytes } from 'node:crypto'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { setTimeout as sleep } from 'node:timers/promises'
import { appHostname, hooksHostname, towerHostname } from '@hangar/shared'
import { stringify } from 'yaml'

export interface AppRoute {
  name: string
  /** Custom domains, served on the public entrypoint only (they arrive through the tunnel). */
  domains?: string[]
  /** null when the app has no running container; the fallback router then sends LAN visitors to core. */
  target: { host: string; port: number } | null
}

export interface RoutingInput {
  lanIp: string
  lanDomain: string
  publicDomain: string | null
  exposeTowerPublicly: boolean
  coreUrl: string
  apps: AppRoute[]
}

interface Router {
  entryPoints: ('web' | 'public')[]
  rule: string
  service: string
  priority?: number
  middlewares?: string[]
}

interface Service {
  loadBalancer: { servers: { url: string }[] }
}

interface HeaderMiddleware {
  headers: { customRequestHeaders: Record<string, string> }
}

export interface DynamicConfig {
  http: {
    routers: Record<string, Router>
    services: Record<string, Service>
    middlewares: Record<string, HeaderMiddleware>
  }
}

/** Set by Traefik on every request to core, overwriting anything the client sent. */
export const ENTRYPOINT_HEADER = 'X-Hangar-Entrypoint'

const CORE = 'core'
const FROM_WEB = 'from-web'
const FROM_PUBLIC = 'from-public'

const host = (hostname: string) => `Host(\`${hostname}\`)`
const loadBalancer = (url: string): Service => ({ loadBalancer: { servers: [{ url }] } })
const entrypointHeader = (value: string): HeaderMiddleware => ({
  headers: { customRequestHeaders: { [ENTRYPOINT_HEADER]: value } },
})

export const appServiceName = (projectName: string) => `app-${projectName}`

/** The URL Traefik forwards an app's traffic to. `waitForService` matches it exactly. */
export const appUpstreamUrl = (target: { host: string; port: number }) =>
  `http://${target.host}:${target.port}`

export function renderRouting(input: RoutingInput): DynamicConfig {
  const { lanIp, lanDomain, publicDomain } = input
  const routers: Record<string, Router> = {}
  const services: Record<string, Service> = { [CORE]: loadBalancer(input.coreUrl) }
  const middlewares = {
    [FROM_WEB]: entrypointHeader('web'),
    [FROM_PUBLIC]: entrypointHeader('public'),
  }

  routers.tower = {
    entryPoints: ['web'],
    rule: `${host(towerHostname(lanDomain))} || ${host(lanIp)}`,
    service: CORE,
    middlewares: [FROM_WEB],
  }
  // Unknown or stopped apps on the LAN get a friendly page from core. Public traffic gets Traefik's plain 404.
  routers.fallback = {
    entryPoints: ['web'],
    rule: 'PathPrefix(`/`)',
    priority: 1,
    service: CORE,
    middlewares: [FROM_WEB],
  }

  if (publicDomain) {
    routers.hooks = {
      entryPoints: ['public'],
      rule: `${host(hooksHostname(publicDomain))} && PathPrefix(\`/api/webhooks/\`)`,
      service: CORE,
      middlewares: [FROM_PUBLIC],
    }
    if (input.exposeTowerPublicly) {
      routers['tower-public'] = {
        entryPoints: ['public'],
        rule: host(towerHostname(publicDomain)),
        service: CORE,
        middlewares: [FROM_PUBLIC],
      }
    }
  }

  const apps = [...input.apps].sort((a, b) => a.name.localeCompare(b.name))
  for (const app of apps) {
    if (!app.target) continue
    const service = appServiceName(app.name)
    services[service] = loadBalancer(appUpstreamUrl(app.target))
    routers[`app-${app.name}`] = {
      entryPoints: ['web'],
      rule: host(appHostname(app.name, lanDomain)),
      service,
    }
    if (publicDomain) {
      routers[`app-${app.name}-public`] = {
        entryPoints: ['public'],
        rule: host(appHostname(app.name, publicDomain)),
        service,
      }
    }
    if (app.domains?.length) {
      routers[`app-${app.name}-domains`] = {
        entryPoints: ['public'],
        rule: app.domains.map(host).join(' || '),
        service,
      }
    }
  }

  return { http: { routers, services, middlewares } }
}

const FILE_HEADER = '# Generated by Hangar from its database. Manual edits are overwritten.\n'

export function createProxy(options: { dynamicDir: string; apiUrl: string }) {
  const file = path.join(options.dynamicDir, 'hangar.yml')

  return {
    /** Writes the routing file atomically. Returns false when nothing changed. */
    async apply(config: DynamicConfig): Promise<boolean> {
      const content = FILE_HEADER + stringify(config)
      const current = await readFile(file, 'utf8').catch(() => null)
      if (current === content) return false
      await mkdir(options.dynamicDir, { recursive: true })
      // Traefik only loads .yml/.yaml/.toml files, so the temp file is ignored until renamed.
      const temp = path.join(options.dynamicDir, `.hangar.${randomBytes(4).toString('hex')}.tmp`)
      await writeFile(temp, content)
      await rename(temp, file)
      return true
    },

    /** Resolves once Traefik reports that `service` forwards to `url`. */
    async waitForService(service: string, url: string, timeoutMs = 10_000): Promise<void> {
      const deadline = Date.now() + timeoutMs
      const endpoint = `${options.apiUrl}/api/http/services/${service}@file`
      while (Date.now() < deadline) {
        const response = await fetch(endpoint).catch(() => null)
        if (response?.ok) {
          const body = (await response.json()) as Partial<Service>
          if (body.loadBalancer?.servers?.some((server) => server.url === url)) return
        }
        await sleep(200)
      }
      throw new Error(
        `Traefik did not pick up the route for ${service} within ${timeoutMs / 1000}s`,
      )
    },
  }
}

export type Proxy = ReturnType<typeof createProxy>
